package types

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// generatedMarker 面板生成的配置的首行标记
const generatedMarker = "# Auto-generated by AcePanel. DO NOT EDIT MANUALLY!"

// disableConf 站点停用的标记片段，存在即为停用
const disableConf = "00-disable.conf"

// Fragments 站点配置目录下 site 与 shared 两级片段文件的读写，各方言的 vhost 内嵌它
type Fragments struct {
	ConfigDir string
}

func (f Fragments) Enable() bool {
	_, err := os.Stat(f.path(disableConf, ScopeSite))
	return os.IsNotExist(err)
}

// SetEnableWith 启用时删掉停用片段，停用时写入 rules。停用规则各方言不同，由各自的 SetEnable 给出
func (f Fragments) SetEnableWith(enable bool, rules string) error {
	path := f.path(disableConf, ScopeSite)
	if enable {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("failed to remove disable config: %w", err)
		}
		return nil
	}
	if err := os.WriteFile(path, []byte(generatedMarker+"\n"+rules), 0600); err != nil {
		return fmt.Errorf("failed to write disable config: %w", err)
	}
	return nil
}

func (f Fragments) Config(name string, scope ConfigScope) string {
	content, err := os.ReadFile(f.path(name, scope))
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(content))
}

func (f Fragments) SetConfig(name string, scope ConfigScope, content string) error {
	return f.writeConfig(name, scope, generatedMarker+"\n"+content)
}

func (f Fragments) SetRawConfig(name string, scope ConfigScope, content string) error {
	return f.writeConfig(name, scope, content)
}

func (f Fragments) RemoveConfig(name string, scope ConfigScope) error {
	if err := os.Remove(f.path(name, scope)); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to remove config file: %w", err)
	}
	return nil
}

func (f Fragments) writeConfig(name string, scope ConfigScope, content string) error {
	if err := os.WriteFile(f.path(name, scope), []byte(content), 0600); err != nil {
		return fmt.Errorf("failed to write config file: %w", err)
	}
	return nil
}

func (f Fragments) path(name string, scope ConfigScope) string {
	return filepath.Join(f.ConfigDir, string(scope), name)
}
