package apache

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/acepanel/panel/v3/pkg/webserver/conf"
	"github.com/acepanel/panel/v3/pkg/webserver/types"
)

// leastConnMethod Apache 只有按请求数、按流量、按繁忙度三种算法，最少连接对应按繁忙度，其余算法表达不了，一律轮询
const leastConnMethod = "bybusyness"

var balancerFilePattern = regexp.MustCompile(`^(\d{3})-balancer-(.+)\.conf$`)

// parseBalancerFiles 从 shared 目录解析所有负载均衡配置（Apache 的 upstream 等价物）
func parseBalancerFiles(sharedDir string) []types.Upstream {
	upstreams := make([]types.Upstream, 0)
	for _, file := range balancerFiles(sharedDir) {
		if upstream := parseBalancerFile(file); upstream != nil {
			upstreams = append(upstreams, *upstream)
		}
	}
	return upstreams
}

// parseBalancerFile 读不出来的文件返回 nil
func parseBalancerFile(filePath string) *types.Upstream {
	cfg, err := ParseFile(filePath)
	if err != nil {
		return nil
	}

	upstream := &types.Upstream{
		Name:     balancerName(filePath),
		Servers:  make(map[string]string),
		Resolver: []string{},
	}

	for _, d := range cfg.Find("IfModule.Proxy.BalancerMember") {
		if len(d.Args) == 0 {
			continue
		}
		addr, options := parseMember(d.Values())
		upstream.Servers[addr] = options
	}

	for _, d := range cfg.Find("IfModule.Proxy.ProxySet") {
		if slices.Contains(d.Values(), "lbmethod="+leastConnMethod) {
			upstream.Algo = types.AlgoLeastConn
		}
	}

	return upstream
}

// parseMember 还原 BalancerMember 为面板的地址与 nginx 风格参数
func parseMember(args []string) (string, string) {
	// 只有套接字写法带 |，后面是编出来的主机名
	addr, _, unix := strings.Cut(args[0], "|")
	if !unix {
		addr = strings.TrimPrefix(addr, "http://")
	}

	var options []string
	for _, a := range args[1:] {
		if a == "upgrade=websocket" {
			continue
		}
		key, value, _ := strings.Cut(a, "=")
		switch key {
		case "loadfactor":
			options = append(options, "weight="+value)
		case "retry":
			options = append(options, "fail_timeout="+value+"s")
		case "status":
			switch value {
			case "+H":
				options = append(options, "backup")
			case "+D":
				options = append(options, "down")
			}
		}
	}
	return addr, strings.Join(options, " ")
}

// balancerNames 上游名从文件名就能取到，不必读内容
func balancerNames(sharedDir string) []string {
	files := balancerFiles(sharedDir)
	names := make([]string, 0, len(files))
	for _, file := range files {
		names = append(names, balancerName(file))
	}
	return names
}

func writeBalancerFiles(sharedDir string, upstreams []types.Upstream) error {
	if len(upstreams) > upstreamEndNum-upstreamStartNum+1 {
		return fmt.Errorf("upstreams exceed limit (%d)", upstreamEndNum-upstreamStartNum+1)
	}
	if err := conf.ClearFiles(sharedDir, balancerFilePattern, upstreamStartNum, upstreamEndNum); err != nil {
		return err
	}

	for i, upstream := range upstreams {
		filePath := filepath.Join(sharedDir, fmt.Sprintf("%03d-balancer-%s.conf", upstreamStartNum+i, upstream.Name))
		if err := os.WriteFile(filePath, []byte(generateBalancerConfig(upstream)), 0600); err != nil {
			return fmt.Errorf("failed to write balancer config: %w", err)
		}
	}

	return nil
}

func generateBalancerConfig(upstream types.Upstream) string {
	proxy := conf.Blk("Proxy", "balancer://"+upstream.Name)
	for _, addr := range slices.Sorted(maps.Keys(upstream.Servers)) {
		proxy.Append(conf.Dir("BalancerMember", balancerMember(addr, upstream.Servers[addr])...))
	}

	method := "byrequests"
	if upstream.Algo == types.AlgoLeastConn {
		method = leastConnMethod
	}
	proxy.Append(conf.Dir("ProxySet", "lbmethod="+method))

	cfg := &conf.Config{}
	cfg.Append(
		conf.Cmt("Auto-generated by AcePanel. DO NOT EDIT MANUALLY!"),
		conf.Cmt("Load balancer: "+upstream.Name),
		conf.Blk("IfModule", "mod_proxy_balancer.c").Append(proxy),
	)
	return Export(cfg) + "\n"
}

// balancerMember 上游地址与参数转 Apache 语法：地址必须带协议前缀，
// 参数名与 nginx 完全不同，照搬过去会让 Apache 以 "unknown Worker parameter" 拒载
func balancerMember(addr, options string) []string {
	args := []string{balancerAddr(addr), "upgrade=websocket"}
	for opt := range strings.FieldsSeq(options) {
		key, value, _ := strings.Cut(opt, "=")
		switch key {
		case "weight":
			args = append(args, "loadfactor="+value)
		case "fail_timeout":
			args = append(args, "retry="+strings.TrimSuffix(value, "s"))
		case "backup":
			args = append(args, "status=+H")
		case "down":
			args = append(args, "status=+D")
		}
	}
	return args
}

func balancerAddr(addr string) string {
	sock, unix := strings.CutPrefix(addr, "unix:")
	switch {
	case strings.Contains(addr, "://"):
		return addr
	case unix:
		return addr + "|http://" + socketHost(sock)
	default:
		return "http://" + addr
	}
}

func balancerFiles(sharedDir string) []string {
	return conf.ListFiles(sharedDir, balancerFilePattern, upstreamStartNum, upstreamEndNum)
}

// balancerName 上游名取自文件名
func balancerName(filePath string) string {
	return balancerFilePattern.FindStringSubmatch(filepath.Base(filePath))[2]
}
